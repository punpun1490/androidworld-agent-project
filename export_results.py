"""Export one AndroidWorld evaluation as an auditable CSV and JSONL trajectory.

Only load checkpoint files generated by this trusted workflow; pickle is unsafe
for untrusted files. Original .pkl.gz files retain full benchmark evidence.
"""
import argparse
import csv
import json
from pathlib import Path
from PIL import Image
import numpy as np

from android_world import checkpointer, constants

FIELDS = [
    "task", "trial_seed", "suite_seed", "model", "agent",
    "success", "steps", "runtime_seconds", "failure_class",
    "recording", "checkpoint_dir",
]


def to_text(value):
    if value is None:
        return None
    if isinstance(value, (bool, int, float, str)):
        return value
    return str(value)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", required=True)
    parser.add_argument("--model", required=True)
    parser.add_argument("--agent", default="m3a_ai_studio")
    parser.add_argument("--suite-seed", type=int, required=True)
    parser.add_argument("--recording", default="recordings/segment_*.mp4")
    args = parser.parse_args()

    root = Path(args.results)
    checkpoint_dirs = sorted(p for p in root.glob("run_*") if p.is_dir())
    if not checkpoint_dirs:
        raise RuntimeError("No AndroidWorld checkpoint directory found")

    E = constants.EpisodeConstants
    rows = []
    trajectory_path = root / "trajectory.jsonl"
    frames = root / "frames"
    frames.mkdir(parents=True, exist_ok=True)

    with trajectory_path.open("w", encoding="utf-8") as out:
        for run_dir in checkpoint_dirs:
            episodes = checkpointer.IncrementalCheckpointer(str(run_dir)).load()
            for episode_index, ep in enumerate(episodes):
                episode_data = ep.get(E.EPISODE_DATA) or {}
                step_ids = episode_data.get(constants.STEP_NUMBER, [])
                task_name = str(ep.get(E.TASK_TEMPLATE, "unknown"))
                trial_seed = ep.get(E.SEED)
                is_successful = bool(ep.get(E.IS_SUCCESSFUL, False))
                error = ep.get(E.EXCEPTION_INFO)
                rows.append({
                    "task": task_name,
                    "trial_seed": trial_seed,
                    "suite_seed": args.suite_seed,
                    "model": args.model,
                    "agent": args.agent,
                    "success": int(is_successful),
                    "steps": len(step_ids),
                    "runtime_seconds": ep.get(E.RUN_TIME),
                    "failure_class": "exception" if error else (
                        "" if is_successful else "task_failure"
                    ),
                    "recording": args.recording,
                    "checkpoint_dir": str(run_dir.relative_to(root)),
                })

                for position, step_id in enumerate(step_ids):
                    def field(name):
                        seq = episode_data.get(name) or []
                        return seq[position] if position < len(seq) else None

                    shot = field("before_screenshot_with_som")
                    frame_file = None
                    if shot is not None:
                        array = np.asarray(shot)
                        if array.dtype != np.uint8:
                            array = np.clip(array, 0, 255).astype(np.uint8)
                        image = Image.fromarray(array).convert("RGB")
                        image.thumbnail((720, 1280))
                        frame = frames / f"{task_name}_{episode_index}_step{position + 1:02d}.jpg"
                        image.save(frame, quality=72, optimize=True)
                        frame_file = str(frame.relative_to(root))

                    raw = field("action_raw_response")
                    record = {
                        "task": task_name,
                        "trial_seed": trial_seed,
                        "model": args.model,
                        "agent": args.agent,
                        "step": int(step_id) + 1,
                        "goal": ep.get(E.GOAL),
                        "reason": to_text(field("action_reason")),
                        "action_output": to_text(field("action_output")),
                        "action_json": to_text(field("action_output_json")),
                        "summary": to_text(field("summary")),
                        "frame": frame_file,
                        "prompt_tokens": raw.get("input_tokens") if isinstance(raw, dict) else None,
                        "output_tokens": raw.get("output_tokens") if isinstance(raw, dict) else None,
                        "final_verifier_success": is_successful,
                    }
                    out.write(json.dumps(record, ensure_ascii=False) + "\n")

    if not rows:
        raise RuntimeError("Checkpoints were present but contained zero episodes")
    with (root / "runs.csv").open("w", encoding="utf-8", newline="") as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print("EVALUATION REPORT")
    for row in rows:
        print(json.dumps(row, ensure_ascii=False))
    print(f"Trajectory: {trajectory_path}; records: {sum(r['steps'] for r in rows)}")


if __name__ == "__main__":
    main()
